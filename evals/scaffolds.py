#!/usr/bin/env python3
"""Generate each live case's `scaffold.sh` from the fixtures it needs.

A live run starts in an empty workspace and cannot read the repository: `context.add_dirs`
refuses a `..` path and does not show a folder inside the case to the agent. So each case that
needs fixtures carries a `scaffold.sh` (run by `claude plugin eval --scaffold` in the workspace
before the agent starts) that writes them out with heredocs. This module is the single source:
edit SCAFFOLDS or a fixture, then run

    python evals/scaffolds.py

and commit the regenerated scripts. tests/skill_evals checks every script is current.
"""

from __future__ import annotations

import sys
from pathlib import Path

EVALS = Path(__file__).resolve().parent
REPO = EVALS.parent
LIVE = EVALS / "live"
DELIMITER = "RQH_FIXTURE_EOF"

_YOLO_SCENARIO = {"evals/replays/yolo/scenario.yaml": "example/scenario.yaml"}
_YOLO_INPUTS = {**_YOLO_SCENARIO, "evals/replays/yolo/inputs.yaml": "example/inputs.yaml"}

# case directory under evals/live/ -> {repository file: workspace path}
SCAFFOLDS: dict[str, dict[str, str]] = {
    "skills/risk-quant/handoff": _YOLO_SCENARIO,
    "skills/collect-data/handoff": _YOLO_SCENARIO,
    "skills/simulate/handoff": _YOLO_INPUTS,
    "skills/report/handoff": _YOLO_INPUTS,
    "skills/risk-quant-resume/handoff": {
        "evals/replays/accuracy/scenario.yaml": "example/scenario.yaml",
        "evals/replays/accuracy/inputs.yaml": "example/inputs.yaml",
        "evals/replays/accuracy/org-profile.yaml": "example/org-profile.yaml",
    },
    "skills/benchmark-researcher/behaviour": {"agents/benchmark-researcher.md": "agents/benchmark-researcher.md"},
}


def render(files: dict[str, str]) -> str:
    """A bash script that writes each repository file, byte for byte (LF), to its workspace path."""
    lines = ["#!/usr/bin/env bash",
             "# Generated by evals/scaffolds.py from the files below; do not edit by hand.",
             "set -euo pipefail"]
    for source, target in files.items():
        text = (REPO / source).read_bytes().decode("utf-8").replace("\r\n", "\n")
        if not text.endswith("\n"):
            raise ValueError(f"{source} must end with a newline to round-trip through a heredoc")
        if DELIMITER in text:
            raise ValueError(f"{source} contains the heredoc delimiter {DELIMITER}")
        parent = Path(target).parent.as_posix()
        lines += ["", f"# {source}"]
        if parent != ".":
            lines.append(f"mkdir -p '{parent}'")
        lines.append(f"cat > '{target}' <<'{DELIMITER}'")
        lines.append(text + DELIMITER)
    return "\n".join(lines) + "\n"


CASE_YAML = 'schema_version: "1.1"\nname: {name}\ncontext:\n  scaffold_script: scaffold.sh\n'


def write_all() -> list[Path]:
    written = []
    for rel, files in SCAFFOLDS.items():
        case = LIVE / rel
        name = _case_name(case)
        for path, text in ((case / "scaffold.sh", render(files)), (case / "case.yaml", CASE_YAML.format(name=name))):
            path.write_bytes(text.encode("utf-8"))
            written.append(path)
    return written


def _case_name(case: Path) -> str:
    for line in (case / "prompt.md").read_text(encoding="utf-8").splitlines():
        if line.startswith("name:"):
            return line.split(":", 1)[1].strip()
    raise ValueError(f"{case}/prompt.md has no name")


if __name__ == "__main__":
    for path in write_all():
        print(path.relative_to(REPO).as_posix())
    sys.exit(0)
